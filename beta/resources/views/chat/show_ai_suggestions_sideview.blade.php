    /*
    |--------------------------------------------------------------------------
    | Know More
    |--------------------------------------------------------------------------
    */

    $(document).on('click', '.know-more-btn', function() {

        const button = $(this);

        const topic = button.data('topic');

        const conversationId = $('#conversation-id').val();

        const single = button.closest('.single');

        const content = single.find('.copycontent');

        if (!conversationId || !topic) {
            return;
        }

        /*
        |--------------------------------------------------------------------------
        | Loading
        |--------------------------------------------------------------------------
        */

        button.prop('disabled', true);

        button.text('Loading...');

        content.html(`
        <p>Generating details...</p>
    `);

        $.ajax({

            url: "{{ route('ai.chat.summary.detail') }}",

            type: "POST",

            data: {

                _token: "{{ csrf_token() }}",

                conversation_id: conversationId,

                topic: topic

            },

            success: function(response) {

                console.log(
                    'Know More Response:',
                    response
                );

                if (!response.success) {

                    content.html(`
                    <p>
                        ${response.message ||
                        'Unable to generate details.'}
                    </p>
                `);

                    return;
                }

                /*
                |--------------------------------------------------------------------------
                | Response
                |--------------------------------------------------------------------------
                */

                content.html('');

                if (response.content) {

                    content.append(
                        $('<p>').text(response.content)
                    );

                }

            },

            error: function(xhr) {

                console.error(
                    'Know More Error:',
                    xhr.responseJSON
                );

                content.html(`
                <p>
                    ${xhr.responseJSON?.message ||
                    'Unable to load details.'}
                </p>
            `);

            },

            complete: function() {

                button.prop('disabled', false);

                button.text('Know more');

            }

        });

    });

    /*
    |--------------------------------------------------------------------------
    | Full Chat Summary
    |--------------------------------------------------------------------------
    */

    $(document).on('click', '[data-chat-summary]', function(e) {

        e.preventDefault();

        const category = $(this).data('chat-summary');
        const conversationId = $('#conversation-id').val();

        if (!conversationId) {
            console.log('Conversation ID not found.');
            return;
        }

        console.log('Clicked category:', category);

        /*
        |--------------------------------------------------------------------------
        | Show loading
        |--------------------------------------------------------------------------
        */

        $('#conversationOverview').html(`
        <p>Generating ${category} summary...</p>
    `);

        $('#chatSummaryKeyPoints').html(`
        <p>Generating summary...</p>
    `);


        /*
        |--------------------------------------------------------------------------
        | AJAX
        |--------------------------------------------------------------------------
        */

        $.ajax({

            url: "{{ route('ai.chat.summary') }}",

            type: "POST",

            data: {

                _token: "{{ csrf_token() }}",

                conversation_id: conversationId,

                category: category

            },

            success: function(response) {

                console.log('Chat Summary Response:', response);

                if (!response.success) {

                    $('#conversationOverview').html(`
                    <p>
                        ${response.message ||
                        'Unable to generate summary.'}
                    </p>
                `);

                    return;
                }


                /*
                |--------------------------------------------------------------------------
                | Overview
                |--------------------------------------------------------------------------
                */

                $('#conversationOverview').html('');

                if (response.overview) {

                    $('#conversationOverview').append(
                        $('<p>').text(response.overview)
                    );

                }


                /*
                |--------------------------------------------------------------------------
                | Key Points
                |--------------------------------------------------------------------------
                */

                const keyPointsContainer =
                    $('#chatSummaryKeyPoints');

                keyPointsContainer.empty();


                if (Array.isArray(response.key_points)) {

                    response.key_points.forEach(function(point) {

                        const item = $(`
                        <div class="single">

                            <h5>
                                <span></span>

                                <button
                                    type="button"
                                    class="know-more-btn"
                                    data-topic="">
                                    Know more
                                </button>
                            </h5>

                            <div class="copycontent">
                                <p></p>
                            </div>

                        </div>
                    `);


                        item.find('h5 span')
                            .text(point.title || '');


                        item.find('.know-more-btn')
                            .attr(
                                'data-topic',
                                point.topic || ''
                            );


                        item.find('.copycontent p')
                            .text(point.description || '');


                        keyPointsContainer.append(item);

                    });

                }

            },

            error: function(xhr) {

                console.error(
                    'Chat Summary Error:',
                    xhr.responseJSON
                );

                $('#conversationOverview').html(`
                <p>
                    ${xhr.responseJSON?.message ||
                    'Unable to generate conversation summary.'}
                </p>
            `);

            }

        });

    });
</script>
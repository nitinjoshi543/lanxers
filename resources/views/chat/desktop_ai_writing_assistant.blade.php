<script>
    /*
    |--------------------------------------------------------------------------
    | Sync Main Chat Message → AI Writing Assistant
    |--------------------------------------------------------------------------
    */

    $(document).on('input', '#chatMessageInput', function() {

        let message = $(this).val();

        $('#aiWritingMessage').val(message);

        if ($.trim(message) !== '') {

            setAIWritingButtonState('generate');

        } else {

            setAIWritingButtonState('disabled');

        }

    });


    /*
    |--------------------------------------------------------------------------
    | If User Types Directly In AI Writing Assistant
    |--------------------------------------------------------------------------
    */

    $(document).on('input', '#aiWritingMessage', function() {

        let message = $(this).val().trim();

        if (message !== '') {

            setAIWritingButtonState('generate');

        } else {

            setAIWritingButtonState('disabled');

        }

    });


    /*
    |--------------------------------------------------------------------------
    | Generate / Regenerate AI Writing
    |--------------------------------------------------------------------------
    */

    $(document).on('click', '#regenerate', function(e) {

        e.preventDefault();

        let button = $(this);

        let message = $('#aiWritingMessage').val().trim();

        let conversationId = $('#conversation-id').val();


        /*
        |--------------------------------------------------------------------------
        | Don't call API if message is empty
        |--------------------------------------------------------------------------
        */

        if (!message) {

            $('#aiWritingMessage').focus();

            return;

        }


        /*
        |--------------------------------------------------------------------------
        | Disable button while generating
        |--------------------------------------------------------------------------
        */

        button
            .addClass('disabled')
            .css('pointer-events', 'none');


        $('#regenerateText').text('Generating...');


        /*
        |--------------------------------------------------------------------------
        | AJAX
        |--------------------------------------------------------------------------
        */

        $.ajax({

            url: "{{ route('ai.writing.generate') }}",

            type: "POST",

            data: {

                _token: "{{ csrf_token() }}",

                message: message,

                conversation_id: conversationId

            },


            /*
            |--------------------------------------------------------------------------
            | Success
            |--------------------------------------------------------------------------
            */

            success: function(response) {

                console.log('AI Writing Response:', response);


                if (!response.refined_message) {

                    alert(
                        response.message ||
                        'Unable to generate response.'
                    );

                    setAIWritingButtonState('generate');

                    return;

                }


                /*
                |--------------------------------------------------------------------------
                | Professional Response
                |--------------------------------------------------------------------------
                */

                $('.professionAi .single')
                    .removeClass('d-none');


                $('.professionAi .single .text p')
                    .first()
                    .text(response.refined_message);


                /*
                |--------------------------------------------------------------------------
                | Other Options
                |--------------------------------------------------------------------------
                */

                const optionsWrapper =
                    $('.Otheroptions');


                /*
                | Remove old generated options
                */

                optionsWrapper
                    .find('.single')
                    .remove();


                /*
                | Add new options
                */

                if (Array.isArray(response.other_options)) {

                    response.other_options.forEach(function(text) {

                        const item = $(`
                            <div class="single">

                                <div class="text">
                                    <p></p>
                                </div>

                                <button type="button">
                                    Copy
                                </button>

                            </div>
                        `);


                        item.find('.text p')
                            .text(text);


                        optionsWrapper.append(item);

                    });

                }


                /*
                |--------------------------------------------------------------------------
                | IMPORTANT
                |--------------------------------------------------------------------------
                | First successful request:
                |
                | Generate → Regenerate
                |--------------------------------------------------------------------------
                */

                setAIWritingButtonState('regenerate');

            },


            /*
            |--------------------------------------------------------------------------
            | Error
            |--------------------------------------------------------------------------
            */

            error: function(xhr) {

                console.error(
                    'AI Writing Error:',
                    xhr.responseJSON
                );


                alert(
                    xhr.responseJSON?.message ||
                    'AI generation failed.'
                );


                /*
                | Allow user to try again
                */

                setAIWritingButtonState('generate');

            },


            /*
            |--------------------------------------------------------------------------
            | Complete
            |--------------------------------------------------------------------------
            */

            complete: function() {

                button
                    .removeClass('disabled')
                    .css('pointer-events', 'auto');

            }

        });

    });


    /*
    |--------------------------------------------------------------------------
    | Generate / Regenerate Button State
    |--------------------------------------------------------------------------
    */

    function setAIWritingButtonState(state) {

        let button = $('#regenerate');

        let text = $('#regenerateText');


        /*
        |--------------------------------------------------------------------------
        | GENERATE
        |--------------------------------------------------------------------------
        */

        if (state === 'generate') {

            text.text('Generate');

            button
                .removeClass('disabled')
                .css('pointer-events', 'auto');

        }


        /*
        |--------------------------------------------------------------------------
        | REGENERATE
        |--------------------------------------------------------------------------
        */
        else if (state === 'regenerate') {

            text.text('Regenerate');

            button
                .removeClass('disabled')
                .css('pointer-events', 'auto');

        }


        /*
        |--------------------------------------------------------------------------
        | DISABLED
        |--------------------------------------------------------------------------
        */
        else {

            text.text('Generate');

            button
                .addClass('disabled')
                .css('pointer-events', 'none');

        }

    }


    /*
    |--------------------------------------------------------------------------
    | Initial State
    |--------------------------------------------------------------------------
    */

    $(document).ready(function() {

        let message = $('#aiWritingMessage').val().trim();


        if (message !== '') {

            setAIWritingButtonState('generate');

        } else {

            setAIWritingButtonState('disabled');

        }

    });


    /*
    |--------------------------------------------------------------------------
    | Copy AI Suggestions
    |--------------------------------------------------------------------------
    */

    $(document).on(
        'click',
        '.professionAi .single button, .Otheroptions .single button',
        function() {

            let text = $(this)
                .closest('.single')
                .find('p')
                .text()
                .trim();


            if (!text) {
                return;
            }


            navigator.clipboard.writeText(text)
                .then(() => {

                    let button = $(this);

                    let oldText = button.text();

                    button.text('Copied');

                    setTimeout(function() {

                        button.text(oldText);

                    }, 1500);

                })
                .catch(function(error) {

                    console.error(
                        'Copy failed:',
                        error
                    );

                });

        }
    );
</script>